"""Chebyshev tables for the Fresnel auxiliary functions f(x), g(x) used by crates/sim/src/fresnel.rs.

C(x) = 1/2 + f sin(pi x^2/2) - g cos(pi x^2/2),  S(x) = 1/2 - f cos(pi x^2/2) - g sin(pi x^2/2).
f and g are smooth, so a degree-14 Chebyshev interpolant per interval reproduces scipy.special.fresnel
to ~1e-15 (printed below) at a fraction of the cost of the continued fraction.

Run from research/:  .venv/bin/python tools/fit_fresnel_aux.py
Writes crates/sim/src/fresnel_tables.rs.
"""
import os
import numpy as np
from numpy.polynomial import chebyshev as ch
from scipy.special import fresnel

INTERVALS = [(1.5, 2.5), (2.5, 4.0), (4.0, 6.0)]
DEGREE = 14
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "crates", "sim", "src", "fresnel_tables.rs")


def auxiliary(x):
    s, c = fresnel(x)
    theta = np.pi * x * x / 2
    f = (0.5 - s) * np.cos(theta) + (c - 0.5) * np.sin(theta)
    g = (0.5 - s) * np.sin(theta) - (c - 0.5) * np.cos(theta)
    return f, g


def fit(lo, hi):
    n = DEGREE + 1
    nodes = np.cos(np.pi * (np.arange(n) + 0.5) / n)
    f, g = auxiliary(lo + (hi - lo) * (nodes + 1) / 2)
    cf, cg = ch.chebfit(nodes, f, DEGREE), ch.chebfit(nodes, g, DEGREE)
    x = np.linspace(lo, hi, 20001)
    u = 2 * (x - lo) / (hi - lo) - 1
    theta = np.pi * x * x / 2
    fa, ga = ch.chebval(u, cf), ch.chebval(u, cg)
    s, c = fresnel(x)
    error = max(np.abs(0.5 - fa * np.cos(theta) - ga * np.sin(theta) - s).max(),
                np.abs(0.5 + fa * np.sin(theta) - ga * np.cos(theta) - c).max())
    print(f"[{lo}, {hi}] max |error| vs scipy {error:.2e}")
    return cf, cg


def rust_array(values):
    return "[" + ", ".join(repr(float(v)) for v in values) + "]"


def main():
    rows = []
    for lo, hi in INTERVALS:
        cf, cg = fit(lo, hi)
        rows.append(f"    AuxiliaryTable {{ from: {lo!r}, to: {hi!r}, f: {rust_array(cf)}, g: {rust_array(cg)} }},")
    source = (
        "//! Generated by research/tools/fit_fresnel_aux.py: Chebyshev coefficients of the Fresnel auxiliary\n"
        "//! functions f(x), g(x) on a few intervals (do not edit by hand).\n\n"
        f"pub const DEGREE: usize = {DEGREE};\n\n"
        "pub struct AuxiliaryTable {\n    pub from: f64,\n    pub to: f64,\n"
        "    pub f: [f64; DEGREE + 1],\n    pub g: [f64; DEGREE + 1],\n}\n\n"
        "#[rustfmt::skip]\n"
        f"pub const TABLES: [AuxiliaryTable; {len(rows)}] = [\n" + "\n".join(rows) + "\n];\n"
    )
    open(OUT, "w").write(source)


if __name__ == "__main__":
    main()
